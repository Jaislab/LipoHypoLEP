"""Publication figure templates. All lettering is explicitly Nimbus Sans.

Run: MPLCONFIGDIR=/tmp/lipohypolep-mpl python make_figures.py
No biological measurements or statistical results are generated by this script.
"""
from pathlib import Path
import json
import os
os.environ.setdefault('MPLCONFIGDIR', '/tmp/lipohypolep-mpl')
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib import font_manager as fm
from matplotlib.ft2font import FT2Font
from matplotlib.patches import Circle, FancyArrowPatch, Rectangle
from matplotlib.text import Text
from PIL import Image
import numpy as np
import fitz

ROOT = Path(__file__).resolve().parent
W, H, DPI = 1536, 1024, 100
FONTROOT = Path(os.environ.get('NIMBUS_SANS_FONT_DIR', '/usr/share/fonts/opentype/urw-base35'))
REGULAR = FONTROOT / 'NimbusSans-Regular.otf'
BOLD = FONTROOT / 'NimbusSans-Bold.otf'
for p in (REGULAR, BOLD):
    if not p.is_file():
        raise RuntimeError(f'Required font unavailable: {p}. Do not substitute a font.')
    fm.fontManager.addfont(str(p))
    assert fm.FontProperties(fname=str(p)).get_name() == 'Nimbus Sans'

plt.rcParams.update({
    'font.family': 'Nimbus Sans', 'svg.fonttype': 'path',
    'pdf.fonttype': 42, 'ps.fonttype': 42, 'axes.unicode_minus': True,
    'text.usetex': False, 'savefig.facecolor': 'white',
})
C = dict(ink='#293331', muted='#69726F', line='#D5DBD8', axis='#A4ADA8',
         S='#D3A297', Sf='#F7EDE9', L='#9CB8A4', Lf='#EDF3EE',
         K='#A4B5C3', Kf='#EEF2F5', quiet='#929B96')
FONTS = {'regular': str(REGULAR), 'bold': str(BOLD)}
AUDIT = []

def canvas():
    fig = plt.figure(figsize=(W/DPI, H/DPI), dpi=DPI, facecolor='white')
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set(xlim=(0, W), ylim=(H, 0))
    ax.axis('off')
    return fig, ax

def txt(ax, x, y, s, size=24, weight='regular', color=None, ha='left', va='baseline', rotation=0):
    fp = fm.FontProperties(fname=FONTS[weight], size=size*72/DPI)
    missing = set(map(ord, s.replace('\n', ''))) - FT2Font(FONTS[weight]).get_charmap().keys()
    if missing:
        raise RuntimeError(f'Glyphs missing from Nimbus Sans in {s!r}: {missing}')
    return ax.text(x, y, s, fontproperties=fp, color=color or C['ink'],
                   ha=ha, va=va, rotation=rotation, parse_math=False,
                   linespacing=1.2, clip_on=False)

def line(ax, x1, y1, x2, y2, color=None, lw=1):
    ax.plot([x1,x2], [y1,y2], color=color or C['line'], lw=lw*72/DPI,
            solid_capstyle='round', clip_on=False)

def arrow(ax, x1, y1, x2, y2, color=None, lw=1.6):
    ax.add_patch(FancyArrowPatch((x1,y1), (x2,y2), arrowstyle='-|>',
                                mutation_scale=11, linewidth=lw*72/DPI,
                                color=color or C['axis'], shrinkA=0, shrinkB=0))

def badge(ax, x, y, group, r=22):
    ax.add_patch(Circle((x,y), r, facecolor=C[group+'f'],
                        edgecolor=C[group], linewidth=1.2*72/DPI))
    txt(ax, x, y+1, group, 25, 'bold', ha='center', va='center')

def panel(ax, x, y, letter, title):
    txt(ax,x,y,letter,34,'bold')
    txt(ax,x+43,y,title,29,'bold')

def header(ax, title, subtitle):
    txt(ax,64,47,'HYPOTHALAMIC BULK RNA SEQUENCING',19,color=C['muted'])
    txt(ax,64,103,title,44,'bold')
    txt(ax,64,143,subtitle,24,color=C['muted'])
    line(ax,64,170,1472,170)

def rich(ax, x, y, pieces, size=23, rotation=0, color=None, align='left'):
    """Set real sub/superscripts without mathtext or fallback fonts.

    Each piece: (text, relative_size, baseline_offset_px), offset > 0 is subscript.
    """
    renderer=ax.figure.canvas.get_renderer()
    widths=[]
    for s, scale, shift in pieces:
        fp=fm.FontProperties(fname=str(REGULAR),size=size*scale*72/DPI)
        widths.append(renderer.get_text_width_height_descent(s,fp,ismath=False)[0])
    cursor=-sum(widths)/2 if align=='center' else -sum(widths) if align=='right' else 0
    for (s,scale,shift),width in zip(pieces,widths):
        if rotation==90:
            txt(ax,x+shift,y-cursor,s,size*scale,rotation=90,color=color)
        else:
            txt(ax,x+cursor,y+shift,s,size*scale,color=color)
        cursor+=width

def save(fig, name):
    fig.canvas.draw()
    letters=[]
    renderer=fig.canvas.get_renderer()
    for t in fig.findobj(Text):
        if not t.get_text(): continue
        path=t.get_fontproperties().get_file()
        if path not in FONTS.values():
            raise RuntimeError(f'Unexpected font: {t.get_text()!r} -> {path}')
        bbox=t.get_window_extent(renderer)
        if bbox.x0 < -1 or bbox.y0 < -1 or bbox.x1 > W+1 or bbox.y1 > H+1:
            raise RuntimeError(f'Text outside canvas: {t.get_text()} {bbox.bounds}')
        letters.append({'text':t.get_text(),'font':Path(path).name,'size_px':round(t.get_fontsize()*DPI/72,1)})
    for ext in ('png','svg'):
        fig.savefig(ROOT/f'{name}.{ext}',dpi=DPI,bbox_inches=None,pad_inches=0)
    svg_path = ROOT/f'{name}.svg'
    svg_path.write_text('\n'.join(row.rstrip() for row in svg_path.read_text().splitlines())+'\n')
    # Convert the outlined SVG to PDF so no reader can substitute a font.
    # This also avoids the CFF/Type42 mismatch produced by Matplotlib with OTF.
    with fitz.open(ROOT/f'{name}.svg') as vector:
        (ROOT/f'{name}.pdf').write_bytes(vector.convert_to_pdf())
    # 300 dpi export preserves the same aspect ratio and vector layout.
    fig.savefig(ROOT/f'{name}_300dpi.png',dpi=300,bbox_inches=None,pad_inches=0)
    assert Image.open(ROOT/f'{name}.png').size == (W,H)
    svg=(ROOT/f'{name}.svg').read_text()
    assert '<text' not in svg, 'SVG must outline every label to prevent font substitution.'
    AUDIT.append({'figure':name,'pixels':[W,H],'all_text':'Nimbus Sans',
                  'svg_text':'outlined paths','labels':letters})
    plt.close(fig)

def study_design():
    fig,ax=canvas()
    header(ax,'Hypothalamic response to leptin in lipodystrophy',
           'Study design and planned differential-expression analysis')
    panel(ax,64,219,'A','Cohorts and tissue workflow')

    groups=[('S',287,'LD + saline','Untreated lipodystrophy'),
            ('L',385,'LD + leptin','Leptin-treated lipodystrophy'),
            ('K',483,'Non-LD control','Non-lipodystrophic mice')]
    for group,y,title,desc in groups:
        badge(ax,91,y,group,23)
        txt(ax,133,y-3,title,28,'bold')
        txt(ax,133,y+29,desc,22,color=C['muted'])
        line(ax,492,y,553,y,C['axis'],1.35)
    line(ax,553,287,553,483,C['axis'],1.35)
    arrow(ax,553,385,614,385)
    # Place the generated anatomical artwork unchanged as a standalone figure asset.
    brain=ROOT/'assets'/'mouse_brain_sagittal.png'
    if not brain.is_file(): raise RuntimeError('Missing mouse-brain illustration asset')
    ax.imshow(np.asarray(Image.open(brain)),extent=(626,1016,514,254),zorder=-1)
    txt(ax,814,532,'Hypothalamus',27,'bold',ha='center')
    arrow(ax,1021,385,1090,385)
    # Short sequencing reads; schematic icon, not measured expression.
    for i,(start,width,col) in enumerate([(0,112,'K'),(18,106,'L'),(4,120,'S'),(30,94,'K'),(13,104,'L')]):
        y=326+i*19
        ax.add_patch(Rectangle((1133+start,y),width,7,facecolor=C[col],edgecolor='none'))
    txt(ax,1200,454,'Bulk RNA-seq',28,'bold',ha='center')
    txt(ax,1200,487,'Gene-level expression',22,color=C['muted'],ha='center')
    rich(ax,64,570,[('All cohorts: LDLR',1,0),('−/−',.72,-8),(' background.',1,0)],size=22,color=C['muted'])
    line(ax,64,599,1472,599)
    panel(ax,64,652,'B','Planned contrasts')
    panel(ax,963,652,'C','Joint interpretation')
    line(ax,924,635,924,923)

    contrasts=[('L','S',717,'Leptin treatment effect','Response within lipodystrophic mice'),
               ('S','K',810,'Untreated LD phenotype','Baseline LD-associated differences'),
               ('L','K',903,'Differences after leptin','Persistent and/or treatment-induced changes')]
    for first,second,y,title,desc in contrasts:
        badge(ax,86,y-5,first,21)
        txt(ax,133,y+3,'vs',23,color=C['muted'],ha='center')
        badge(ax,179,y-5,second,21)
        txt(ax,224,y-6,title,28,'bold')
        txt(ax,224,y+25,desc,21,color=C['muted'])
    for y in (759,852): line(ax,64,y,886,y)

    txt(ax,963,689,'Compare direction and effect size',22,color=C['muted'])
    for y,title,desc,col in [(742,'Shift toward control','LD change moves toward K','L'),
                             (823,'Persistent difference','LD-associated change remains','S'),
                             (904,'Treatment-associated change','Interpret alongside baseline LD','K')]:
        line(ax,966,y-23,966,y+20,C[col],4)
        txt(ax,987,y-1,title,26,'bold')
        txt(ax,987,y+26,desc,21,color=C['muted'])

    line(ax,64,958,1472,958)
    txt(ax,64,994,'Analysis plan only; no expression data shown.',21,color=C['muted'])
    rich(ax,1472,994,[('Positive log',1,0),('2',.72,5),('FC: higher in the first group',1,0)],
         size=21,color=C['muted'],align='right')
    save(fig,'01_study_design')

def volcano_template():
    fig,ax=canvas()
    header(ax,'Differential expression across the three contrasts',
           'Plot template • gene positions, thresholds and labels will follow the DEG tables')
    panels=[(64,'A','L','S','Leptin treatment effect'),
            (551,'B','S','K','Untreated LD phenotype'),
            (1038,'C','L','K','Differences after leptin')]
    for left,letter,first,second,title in panels:
        txt(ax,left,232,letter,34,'bold')
        badge(ax,left+91,221,first,20)
        txt(ax,left+137,229,'vs',23,color=C['muted'],ha='center')
        badge(ax,left+184,221,second,20)
        txt(ax,left,277,title,27,'bold')
        x0,x1,y0,y1=left+61,left+419,337,780
        mid=(x0+x1)/2
        line(ax,x0,y0,x0,y1,C['axis'],1.2)
        line(ax,x0,y1,x1,y1,C['axis'],1.2)
        ax.plot([mid,mid],[y0,y1],color=C['line'],lw=.8,ls=(0,(4,5)))
        line(ax,mid,y1,mid,y1+7,C['axis'],1.2)
        txt(ax,mid,y1+36,'0',23,color=C['muted'],ha='center')
        txt(ax,mid,551,'DEG table pending',26,color=C['quiet'],ha='center')
        txt(ax,mid,584,'No data plotted',22,color=C['quiet'],ha='center')
        rich(ax,mid,854,[('log',1,0),('2',.72,5),(' fold change',1,0)],size=25,align='center')
        rich(ax,left+18,558,[('−log',1,0),('10',.72,5),('(adjusted P)',1,0)],size=23,rotation=90,align='center')
        arrow(ax,mid-6,895,x0+24,895,C['axis'],1.1)
        arrow(ax,mid+6,895,x1-24,895,C['axis'],1.1)
        txt(ax,x0+16,929,f'Higher in {second}',22,color=C['muted'])
        txt(ax,x1-16,929,f'Higher in {first}',22,color=C['muted'],ha='right')
    line(ax,64,959,1472,959)
    txt(ax,64,995,'S  LD + saline     L  LD + leptin     K  Non-LD control',21,color=C['muted'])
    txt(ax,1472,995,'No significance cutoff assumed',21,color=C['muted'],ha='right')
    save(fig,'02_volcano_template')

